const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const root=path.join(__dirname,"..");
const app=fs.readFileSync(path.join(root,"app.js"),"utf8");
const csv=fs.readFileSync(path.join(root,"temporary-imports","asher-homework-2026-09-28.csv"),"utf8");
const start=app.indexOf("function parseCSV(text)"),end=app.indexOf("  function importHomeworkCSV(file)",start);
assert(start>=0&&end>start,"Could not locate the Mission Board CSV parser");
const isoLocal=date=>`${date.getFullYear()}-${String(date.getMonth()+1).padStart(2,"0")}-${String(date.getDate()).padStart(2,"0")}`;
const homeworkTasksFromCSV=Function("isoLocal",`${app.slice(start,end)};return homeworkTasksFromCSV;`)(isoLocal);
const tasks=homeworkTasksFromCSV(csv);
assert.equal(tasks.length,22,"The weekly homework file should contain 22 assignments");
assert.equal(tasks.filter(task=>task.week==="2026-09-28").length,21,"The September 28 Mission Board week should contain 21 assignments");
assert.equal(tasks.filter(task=>task.week==="2026-10-05").length,1,"The October 9 recitation should appear in the following week");
assert(tasks.some(task=>task.subject==="Grammar, Writing"&&task.title==="Take spelling quiz"),"Quoted CSV subjects were not parsed correctly");
assert(tasks.some(task=>task.day===6&&task.title.includes("IXL lessons")),"Sunday IXL work was assigned to the wrong day");
assert.throws(()=>homeworkTasksFromCSV("date,assignment\nnot-a-date,Test"),/invalid date/);
assert.throws(()=>homeworkTasksFromCSV("subject,assignment\nMath,Test"),/date and assignment/);
console.log("Validated 22 Mission Board assignments, dates, quoted fields, week grouping, and error handling.");
