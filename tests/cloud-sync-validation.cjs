const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const root=path.join(__dirname,"..");
const app=fs.readFileSync(path.join(root,"app.js"),"utf8");
const html=fs.readFileSync(path.join(root,"index.html"),"utf8");
const cloud=fs.readFileSync(path.join(root,"cloud-sync.js"),"utf8");
const config=fs.readFileSync(path.join(root,"cloud-config.js"),"utf8");
const rules=fs.readFileSync(path.join(root,"firestore.rules"),"utf8");
const worker=fs.readFileSync(path.join(root,"sw.js"),"utf8");
assert(config.includes("window.LEARNING_ARCADE_FIREBASE = null"),"Cloud config should be safe and unconfigured by default");
assert(cloud.includes("firebasejs/12.19.0/firebase-app.js"),"Pinned official Firebase web module is missing");
for(const method of ["createAccount","signIn","signOut","push:upload","pull","schedulePush"])assert(cloud.includes(method),`Missing cloud method: ${method}`);
assert(rules.includes("request.auth.uid == userId"),"Firestore saves are not owner protected");
assert(app.includes("LearningArcadeDataBridge"),"The local data bridge is missing");
for(const marker of ["Cloud Save setup needed","cloudCreateAccount","cloudPush","cloudPull","learning-arcade-cloud-state"])assert(app.includes(marker),`Missing Cloud Save UI marker: ${marker}`);
assert(html.includes('src="cloud-config.js?v=34"')&&html.includes('type="module" src="cloud-sync.js?v=34"'),"Cloud scripts are not loaded in the expected order");
assert(worker.includes('"./cloud-config.js","./cloud-sync.js"'),"Cloud files are missing from the offline shell");
console.log("Validated opt-in Cloud Save wiring, owner-only rules, local bridge, settings controls, and offline shell files.");
